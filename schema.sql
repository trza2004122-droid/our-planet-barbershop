-- Our Planet Barbershop - Supabase schema
-- Run this in Supabase SQL Editor. Uses Cairo local business hours at the application layer.
create extension if not exists btree_gist;

create table if not exists public.barbers (
  id bigint generated by default as identity primary key,
  name text not null unique,
  active boolean not null default true
);
create table if not exists public.services (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  duration_minutes integer not null check (duration_minutes > 0),
  price_egp numeric(10,2) not null check (price_egp >= 0),
  active boolean not null default true
);
create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null unique,
  created_at timestamptz not null default now()
);
create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  booking_code text not null unique,
  customer_id bigint not null references public.customers(id),
  barber_id bigint not null references public.barbers(id),
  service_id bigint not null references public.services(id),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  status text not null default 'confirmed' check(status in ('confirmed','pending_payment','cancelled','completed','expired')),
  payment_method text not null check(payment_method in ('pay_at_shop','online')),
  payment_status text not null default 'unpaid' check(payment_status in ('unpaid','pending','paid','failed','refunded')),
  hold_expires_at timestamptz,
  created_at timestamptz not null default now(),
  check(ends_at > starts_at),
  constraint no_barber_overlap exclude using gist (
    barber_id with =,
    tstzrange(starts_at, ends_at, '[)') with &&
  ) where (status in ('confirmed','pending_payment'))
);
create index if not exists bookings_starts_at_idx on public.bookings(starts_at);
create index if not exists bookings_customer_idx on public.bookings(customer_id);

