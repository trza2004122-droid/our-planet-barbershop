-- Public booking RPC. Expired payment holds are cleared before inserting.
create or replace function public.create_booking(
  p_customer_name text,
  p_customer_phone text,
  p_barber_name text,
  p_service_code text,
  p_starts_at timestamptz,
  p_payment_method text default 'pay_at_shop'
) returns table(booking_code text)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_customer_id bigint;
  v_barber_id bigint;
  v_service_id bigint;
  v_duration integer;
  v_code text;
begin
  if p_payment_method <> 'pay_at_shop' then
    raise exception 'Online payment is not enabled yet';
  end if;
  if length(trim(p_customer_name)) < 2 or p_customer_phone !~ '^01[0-9]{9}$' then
    raise exception 'Invalid customer details';
  end if;
  if p_starts_at <= now() then raise exception 'Selected time is in the past'; end if;

  update bookings
    set status='expired', payment_status='failed'
    where status='pending_payment' and hold_expires_at < now();

  select id into v_barber_id from barbers where name=p_barber_name and active=true;
  if v_barber_id is null then raise exception 'Barber not found'; end if;
  select id,duration_minutes into v_service_id,v_duration from services where code=p_service_code and active=true;
  if v_service_id is null then raise exception 'Service not found'; end if;

  insert into customers(name,phone) values(trim(p_customer_name),p_customer_phone)
    on conflict(phone) do update set name=excluded.name
    returning id into v_customer_id;

  v_code := 'OP-' || upper(substr(replace(gen_random_uuid()::text,'-',''),1,8));
  insert into bookings(booking_code,customer_id,barber_id,service_id,starts_at,ends_at,status,payment_method,payment_status)
  values(v_code,v_customer_id,v_barber_id,v_service_id,p_starts_at,p_starts_at+make_interval(mins=>v_duration),'confirmed','pay_at_shop','unpaid');
  return query select v_code;
exception when exclusion_violation then
  raise exception 'This barber already has a booking during that time. Please choose another slot.';
end;
$$;

-- Minimal public permissions. Do not expose customer/bookings tables to anonymous users.
alter table public.barbers enable row level security;
alter table public.services enable row level security;
alter table public.customers enable row level security;
alter table public.bookings enable row level security;
create policy "Public can read active barbers" on public.barbers for select to anon, authenticated using (active=true);
create policy "Public can read active services" on public.services for select to anon, authenticated using (active=true);
revoke all on public.customers from anon, authenticated;
revoke all on public.bookings from anon, authenticated;
grant execute on function public.create_booking(text,text,text,text,timestamptz,text) to anon, authenticated;
